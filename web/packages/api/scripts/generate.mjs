// Generates the client's types and samples from the committed OpenAPI schema:
//   - src/schema.d.ts: the API's types (openapi-typescript);
//   - src/operations.ts: each operation's method and path, by operationId;
//   - src/fixtures.ts: a sample of each list the API answers (what FakeUdl answers with).
// Run it after `python -m udl.interfaces.api.openapi openapi.json`; `--check` fails (exit 1)
// when any of them is out of date, which is what `make check` runs.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = (name) => fileURLToPath(new URL(name, import.meta.url));
const SCHEMA = here("../openapi.json");
const TYPES = here("../src/schema.d.ts");
const OPERATIONS = here("../src/operations.ts");
const FIXTURES = here("../src/fixtures.ts");
const check = process.argv.includes("--check");

const BANNER = "// Generated from openapi.json by scripts/generate.mjs: do not edit.\n";

const document = JSON.parse(await readFile(SCHEMA, "utf8"));
const schemas = document.components?.schemas ?? {};

/** Each operation's id, method and path, sorted by id. */
function operationsOf(schema) {
	const found = [];
	for (const [path, item] of Object.entries(schema.paths ?? {})) {
		for (const [method, operation] of Object.entries(item ?? {})) {
			if (operation && typeof operation === "object" && "operationId" in operation) {
				found.push([String(operation.operationId), method, path]);
			}
		}
	}
	return found.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** The list schema a `list_…` operation answers with, by operationId. */
function listsOf(operations) {
	const found = [];
	for (const [id, method, path] of operations) {
		if (!id.startsWith("list_")) continue;
		const ok =
			document.paths?.[path]?.[method]?.responses?.["200"]?.content?.["application/json"]?.schema;
		const name = ok?.$ref?.split("/").pop();
		if (name?.endsWith("List") && schemas[name]) found.push([id, name]);
	}
	return found.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** A sample of `schema`: its required fields, by type, with the first item of each array a list
 * is made of (so a list is not empty) — the fixtures. */
function sample(schema, depth = 0, seen = new Set()) {
	if (!schema || typeof schema !== "object") return null;
	if (schema.$ref) {
		const name = schema.$ref.split("/").pop();
		if (!name || seen.has(name) || depth > 8) return {};
		return sample(schemas[name], depth + 1, new Set([...seen, name]));
	}
	if (schema.const !== undefined) return schema.const;
	if (schema.enum) return schema.enum[0];
	const anyOf = schema.anyOf ?? schema.oneOf;
	if (anyOf) {
		const branch = anyOf.find((b) => b.type !== "null") ?? anyOf[0];
		return sample(branch, depth, seen);
	}
	if (schema.allOf) {
		return Object.assign({}, ...schema.allOf.map((b) => sample(b, depth, seen)));
	}
	switch (schema.type) {
		case "object": {
			// (The required fields, and the ones with a default: openapi-typescript makes those
			// required too, since the API always sends them.)
			const names = new Set(schema.required ?? []);
			for (const [name, property] of Object.entries(schema.properties ?? {})) {
				if (property && typeof property === "object" && "default" in property) names.add(name);
			}
			const out = {};
			for (const name of [...names].sort()) {
				const property = schema.properties?.[name] ?? {};
				out[name] = "default" in property ? property.default : sample(property, depth + 1, seen);
			}
			return out;
		}
		case "array":
			return depth <= 1 && schema.items ? [sample(schema.items, depth + 1, seen)] : [];
		case "string":
			return schema.format === "date-time" ? "2026-01-01T00:00:00Z" : "text";
		case "integer":
		case "number":
			return 0;
		case "boolean":
			return false;
		default:
			return null;
	}
}

const operations = operationsOf(document);
const lists = listsOf(operations);

const types = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

${astToString(await openapiTS(document))}`;

const operationsSource = `${BANNER}import type { paths } from "./schema";

/** Every operation of udl's API, by operationId: the method it is sent with, and its path. */
export const operations = {
${operations.map(([id, method, path]) => `\t${id}: { method: "${method}", path: "${path}" },`).join("\n")}
} as const satisfies Record<
	string,
	{ method: "get" | "post" | "put" | "patch" | "delete"; path: keyof paths }
>;

export type OperationId = keyof typeof operations;
`;

const fixturesSource = `${BANNER}import type { components } from "./schema";

/** A sample of each list the API answers, by the operation that answers it: what FakeUdl
 * answers with until a test says otherwise. */
export const fixtures = {
${lists
	.map(
		([id, name]) =>
			`\t${id}: ${JSON.stringify(sample(schemas[name]), null, "\t").replaceAll("\n", "\n\t")} satisfies components["schemas"]["${name}"],`,
	)
	.join("\n")}
};
`;

const files = [
	[TYPES, types],
	[OPERATIONS, operationsSource],
	[FIXTURES, fixturesSource],
];

const stale = [];
for (const [path, text] of files) {
	const current = await readFile(path, "utf8").catch(() => "");
	if (current !== text) stale.push(path);
}

if (check) {
	if (stale.length > 0) {
		process.stderr.write(
			`${stale.join(", ")} out of date: run \`pnpm -C web --filter @udl/api run generate\`\n`,
		);
		process.exit(1);
	}
} else {
	for (const [path, text] of files) await writeFile(path, text);
	process.stdout.write(`${operations.length} operations, ${lists.length} fixtures\n`);
}
